function matchTemplate(title: string): Template | null {
  const t = title.trim()
  for (const tpl of TEMPLATES) {
    if (tpl.keys.some((k) => t.includes(k))) return tpl
  }
  return null
}

// صيغة معالجة تتناسب مع شدة القصور
function severityVerb(level: number): string {
  if (level <= 1) return 'المعالجة العاجلة لأوجه القصور في'
  if (level === 2) return 'رفع مستوى'
  return 'تعزيز واستدامة'
}

function rowForAxis(ax: AxisStat): PlanRow {
  const level = ax.band?.level ?? 3
  const tpl = matchTemplate(ax.title_ar)
  return {
    area: `${ax.title_ar} — ${ax.band?.labelAr ?? '—'} (${fmtMean(ax.meanAll)})`,
    action: tpl
      ? tpl.action
      : `${severityVerb(level)} «${ax.title_ar}» عبر تحليل أسباب انخفاض التقييم ووضع إجراءات محددة وقابلة للقياس ومتابعتها دوريًا.`,
    responsible: tpl?.responsible ?? 'رئيس القسم / لجنة الجودة بالبرنامج',
    timeframe: level <= 1 ? 'فوري — خلال الفصل الحالي' : 'الفصل الدراسي القادم',
    indicator:
      tpl?.indicator ?? 'ارتفاع متوسط المحور إلى مستوى «مستوفٍ بإتقان» (≥ 3.5) في الاستطلاع القادم',
  }
}

/**
 * يولّد خطة تحسين حتمية من نتائج الاستطلاع:
 *  - المحاور ذات التقدير «مستوفٍ» فأقل (المستوى ≤ 3) مرتبةً تصاعديًا حسب المتوسط.
 *  - إن كانت كل المحاور قوية، يُنشئ صفوف تحسين مستمر من أدنى الفقرات.
 */
export function generatePlan(data: ReportData): PlanRow[] {
  const weakAxes = data.axes
    .filter((a) => a.meanAll != null && (a.band?.level ?? 5) <= 3)
    .sort((a, b) => (a.meanAll ?? 0) - (b.meanAll ?? 0))

  const rows = weakAxes.map(rowForAxis)

  if (rows.length) {
    // أضف بندًا مركّزًا على أدنى فقرة على مستوى الاستطلاع
    const lowest = data.weaknesses[0]
    if (lowest && lowest.meanAll != null && (lowest.band?.level ?? 5) <= 3) {
      rows.push({
        area: `فقرة مركّزة: ${lowest.text_ar} (${fmtMean(lowest.meanAll)})`,
        action:
          'وضع إجراء تصحيحي محدد لهذه الفقرة الأدنى تقييمًا مع تحديد المسؤول والمهلة الزمنية ومتابعة أثره في الاستطلاع القادم.',
        responsible: 'رئيس القسم / منسق البرنامج',
        timeframe: 'الفصل الدراسي القادم',
        indicator: `ارتفاع متوسط الفقرة إلى ≥ 3.5 في الاستطلاع القادم`,
      })
    }
    return rows
  }

  // كل المحاور بمستوى جيد — خطة تحسين مستمر من أدنى الفقرات
  return data.weaknesses.slice(0, 3).map((q) => ({
    area: `${q.text_ar} (${fmtMean(q.meanAll)})`,
    action:
      'المحافظة على مستوى الأداء المتميز وتعزيزه عبر تعميم أفضل الممارسات ومتابعة رضا المستفيدين بشكل دوري.',
    responsible: 'منسق البرنامج / لجنة الجودة',
    timeframe: 'خلال العام الأكاديمي',
    indicator: 'المحافظة على التقدير «مستوفٍ بإتقان» فأعلى في الاستطلاع القادم',
  }))
}

// ---- التسلسل/التحليل للتخزين في حقل actions النصي (توافق رجعي) ----

export function serializePlanRows(rows: PlanRow[]): string {
  return JSON.stringify(rows)
}

/** يحاول قراءة الصفوف من نص actions؛ يعيد null إذا كان نصًا قديمًا حرًّا. */
export function parsePlanRows(actions: string | null | undefined): PlanRow[] | null {
  if (!actions) return null
  const s = actions.trim()
  if (!s.startsWith('[')) return null
  try {
    const parsed = JSON.parse(s)
    if (!Array.isArray(parsed)) return null
    return parsed
      .filter((r) => r && typeof r === 'object')
      .map((r) => ({
        area: String(r.area ?? ''),
        action: String(r.action ?? ''),
        responsible: String(r.responsible ?? ''),
        timeframe: String(r.timeframe ?? ''),
        indicator: String(r.indicator ?? ''),
      }))
  } catch {
    return null
  }
}

export function emptyPlanRow(): PlanRow {
  return { area: '', action: '', responsible: '', timeframe: 'الفصل الدراسي القادم', indicator: '' }
}
